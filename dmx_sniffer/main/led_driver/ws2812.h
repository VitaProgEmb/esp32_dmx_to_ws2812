/**
 * @file ws2812.h
 * @brief Драйвер адресных светодиодных лент WS2812B через интерфейс RMT ESP32
 *
 * Данный модуль реализует управление двумя независимыми светодиодными лентами
 * WS2812B с использованием аппаратного модуля RMT (Remote Control Transceiver)
 * для точной генерации timings-сигналов. Поддерживается двойная буферизация
 * (double buffering) для безопасной записи данных из разных задач без конфликтов.
 *
 * Архитектура буферов:
 *   - Каждая лента имеет два банка цветов: bank_a и bank_b.
 *   - Указатель colors всегда указывает на текущий "display-банк", данные
 *     которого передаются в RMT для вывода на ленту.
 *   - "back-банк" используется для записи новых данных (через led_set_pixel
 *     или прямой доступ через led_get_colors).
 *   - Вызов led_show() выполняет копирование back-банка в GRB-формат,
 *     отправку через RMT и последующую ротацию банков (swap).
 *
 * Публичный API:
 *   led_init, led_set_pixel, led_show, led_set_count, led_fill, led_clear, led_deinit
 *
 * Внутренний API (для модуля dmx.c — прямой доступ к буферам):
 *   led_lock, led_unlock, led_get_colors, led_get_count, led_swap_banks, led_refresh
 *
 * @note Протокол WS2812B: передача в формате GRB, 800 кбит/с,
 *       минимальный reset-импульс > 50 мкс.
 * @note Зависимости: ESP-IDF RMT driver, FreeRTOS (semaphore).
 */

#pragma once

#include <stdint.h>
#include <stdbool.h>
#include "settings.h"

/* ===== Типы ===== */

/**
 * @struct led_color_t
 * @brief Структура, описывающая цвет одного светодиода WS2812B в формате RGB.
 *
 * Поля хранят компоненты цвета в диапазоне 0–255.
 * При передаче в ленту выполняется конвертация в порядок GRB (см. fill_grb).
 */
typedef struct {
    uint8_t r;  /**< Красная компонента цвета (0–255) */
    uint8_t g;  /**< Зелёная компонента цвета (0–255) */
    uint8_t b;  /**< Синяя компонента цвета (0–255) */
} led_color_t;

/* ===== API ===== */

/**
 * @brief Инициализация одной светодиодной ленты и выделение ресурсов RMT.
 *
 * Создаёт RMT TX-канал, программный кодировщик (encoder) для WS2812B,
 * выделяет GRB-буфер и устанавливает начальные параметры ленты.
 * При первом вызове создаёт мьютекс для синхронизации доступа к буферам.
 *
 * @param strip  Индекс ленты: 0 — первая лента, 1 — вторая лента.
 * @param gpio   Номер GPIO-вывода, к которому подключена лента.
 * @param count  Количество светодиодов в ленте (не более LED_STRIP_MAX_LEDS).
 *
 * @note Если count превышает LED_STRIP_MAX_LEDS, оно будет обрезано до максимума.
 * @note Вызывается один раз при старте системы для каждой ленты.
 */
void led_init(uint8_t strip, uint8_t gpio, uint16_t count);

/**
 * @brief Установить цвет одного светодиода в back-буфере (без вывода на ленту).
 *
 * Записывает RGB-значение в back-банк по указанному индексу. Данные не
 * выводятся на ленту до вызова led_show(). Потокобезопасно: доступ к буферу
 * защищён мьютексом.
 *
 * @param strip  Индекс ленты: 0 или 1.
 * @param idx    Индекс светодиода (0-based, от 0 до count-1).
 * @param r      Красная компонента цвета (0–255).
 * @param g      Зелёная компонента цвета (0–255).
 * @param b      Синяя компонента цвета (0–255).
 *
 * @note Если idx >= count, запись игнорируется (без ошибки).
 */
void led_set_pixel(uint8_t strip, uint16_t idx, uint8_t r, uint8_t g, uint8_t b);

/**
 * @brief Отправить содержимое back-буфера на светодиодную ленту.
 *
 * Выполняет три действия:
 *   1. Конвертацию back-буфера из RGB в формат GRB с учётом опций reverse/shift.
 *   2. Ротацию банков: back-банк становится display-банком.
 *   3. Запуск передачи данных через RMT TX.
 *
 * @param strip  Индекс ленты: 0 или 1.
 *
 * @note Функция блокирующая: ожидает завершения передачи (но не завершения RMT,
 *       которая работает асинхронно через DMA).
 */
void led_show(uint8_t strip);

/**
 * @brief Изменить количество активных светодиодов на ленте «на лету».
 *
 * Обновляет внутренний счётчик count и пересчитывает g_total_leds.
 * Не влияет на выделенную память (она фиксирована LED_STRIP_MAX_LEDS).
 *
 * @param strip  Индекс ленты: 0 или 1.
 * @param count  Новое количество светодиодов (не более LED_STRIP_MAX_LEDS).
 */
void led_set_count(uint8_t strip, uint16_t count);

/**
 * @brief Заполнить все светодиоды ленты одинаковым цветом и вывести на ленту.
 *
 * Устанавливает заданный RGB-цвет для всех LED в back-буфере, затем
 * автоматически вызывает led_show() для обновления вывода.
 *
 * @param strip  Индекс ленты: 0 или 1.
 * @param r      Красная компонента цвета (0–255).
 * @param g      Зелёная компонента цвета (0–255).
 * @param b      Синяя компонента цвета (0–255).
 */
void led_fill(uint8_t strip, uint8_t r, uint8_t g, uint8_t b);

/**
 * @brief Полная очистка всех светодиодов (установка чёрного цвета) и вывод на ленту.
 *
 * Заполняет back-буфер нулевыми значениями (чёрный), затем вызывает led_show().
 *
 * @param strip  Индекс ленты: 0 или 1.
 */
void led_clear(uint8_t strip);

/**
 * @brief Освобождение всех ресурсов модуля LED-драйвера.
 *
 * Освобождает GRB-буферы, удаляет RMT-кодировщики и каналы, удаляет мьютекс.
 * Вызывается при завершении работы или перезагрузке.
 */
void led_deinit(void);

/* ===== Внутренний API (для dmx.c — прямой доступ к буферу) ===== */

/**
 * @brief Захват мьютекса для безопасного доступа к буферу LED.
 *
 * Блокирует мьютекс на неограниченное время. Используется перед прямой
 * записью в back-банк через led_get_colors(). Обязательно вызвать
 * led_unlock() после завершения работы с буфером.
 *
 * @param strip  Индекс ленты (параметр зарезервирован для будущего расширения).
 */
void led_lock(uint8_t strip);

/**
 * @brief Освобождение мьютекса LED-буфера.
 *
 * Снимает блокировку, установленную led_lock(). Должен вызываться
 * в паре с led_lock() после завершения записи в буфер.
 *
 * @param strip  Индекс ленты (параметр зарезервирован для будущего расширения).
 */
void led_unlock(uint8_t strip);

/**
 * @brief Получить указатель на текущий back-буфер цветов для прямой записи.
 *
 * Возвращает указатель на банк, который НЕ используется для вывода в RMT.
 * Потокобезопасно при условии вызова в паре led_lock()/led_unlock().
 *
 * @param strip  Индекс ленты: 0 или 1.
 *
 * @return Указатель на массив led_color_t[] (размер LED_STRIP_MAX_LEDS),
 *         или NULL если strip недопустим.
 *
 * @warning Необходимо вызвать led_lock() перед использованием и led_unlock()
 *          после завершения записи.
 */
led_color_t *led_get_colors(uint8_t strip);

/**
 * @brief Получить текущее количество активных светодиодов на ленте.
 *
 * @param strip  Индекс ленты: 0 или 1.
 *
 * @return Количество LED (0..LED_STRIP_MAX_LEDS), или 0 если strip недопустим.
 */
uint16_t led_get_count(uint8_t strip);

/**
 * @brief Ротация банков (swap) — поменять местами display и back-буферы.
 *
 * После вызова данные, которые были в back-буфере, становятся активными
 * для вывода на следующий вызов led_show() или led_refresh().
 * Не выполняет передачу данных на ленту — только переключает указатели.
 *
 * @param strip  Индекс ленты: 0 или 1.
 */
void led_swap_banks(uint8_t strip);

/**
 * @brief Обновление вывода на ленту без ротации банков (refresh).
 *
 * Конвертирует текущий display-банк в GRB и отправляет через RMT.
 * В отличие от led_show(), не выполняет swap банков. Используется, когда
 * данные уже записаны в display-банк (например, после led_swap_banks
 * или прямой записи через led_get_colors).
 *
 * @param strip  Индекс ленты: 0 или 1.
 */
void led_refresh(uint8_t strip);

/* ===== Глобальные переменные ===== */

/**
 * @brief Общее количество активных светодиодов на обеих лентах.
 *
 * Автоматически пересчитывается при вызове led_init() или led_set_count().
 * Используется модулем dmx.c для расчёта количества приборов.
 */
extern volatile uint16_t g_total_leds;

/**
 * @brief Текущий режим работы двух LED-лент.
 *
 * Определяет, как данные распределяются между лентами:
 *   - LED_MODE_PARALLEL:   параллельный режим (каждая лента от своего DMX-порта).
 *   - LED_MODE_SEQUENTIAL: последовательный режим (одна лента из двух DMX-портов).
 *
 * @see led_mode_t в settings.h
 */
extern volatile led_mode_t g_led_mode;

/**
 * @brief Включить/выключить реверс порядка светодиодов на ленте.
 *
 * При включении (on = true) порядок LED инвертируется: первый физический
 * LED получает данные последнего в массиве, и наоборот. Полезно для
 * компенсации направления подключения ленты.
 *
 * @param strip  Индекс ленты: 0 или 1.
 * @param on     true — реверс включён, false — реверс выключен.
 */
void led_set_reverse(uint8_t strip, bool on);

/**
 * @brief Установить смещение (shift) начала вывода на ленте.
 *
 * Сдвигает начало вывода на указанное количество позиций. Используется
 * для выравнивания начала данных при последовательном режиме (sequential),
 * когда приборы распределены между двумя DMX-портами.
 *
 * @param strip  Индекс ленты: 0 или 1.
 * @param shift  Количество позиций сдвига (0..count-1).
 */
void led_set_shift(uint8_t strip, uint16_t shift);
