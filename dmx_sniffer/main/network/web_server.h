/**
 * @file web_server.h
 * @brief HTTP REST API сервер для веб-интерфейса DMX-сниффера
 *
 * Предоставляет минимальный HTTP API для управления параметрами
 * сниффера DMX, настройки LED-лент и тестирования DMX-каналов.
 * Веб-интерфейс отдаётся как gzip-архив из SPIFFS (index_html_gz).
 *
 * @note Все обработчики вызываются напрямую из HTTP-потока;
 *       блокировки держатся кратко через dmx_lock/dmx_unlock.
 */
#pragma once

#include "esp_err.h"

/**
 * @brief Инициализирует и запускает HTTP-сервер
 *
 * Монтирует SPIFFS, регистрирует все URI-обработчики
 * (GET/POST эндпоинты) и запускает httpd на дефолтном порту (80).
 *
 * @return ESP_OK при успешном запуске, ESP_FAIL при ошибке
 */
esp_err_t web_server_init(void);

/**
 * @brief Останавливает HTTP-сервер и освобождает ресурсы
 *
 * Корректно завершает все активные соединения,
 * останавливает httpd и освобождает дескриптор.
 */
void web_server_stop(void);
