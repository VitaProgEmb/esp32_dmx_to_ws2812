#pragma once

/**
 * @file effects.h
 * @brief Движок LED-эффектов (радужное свечение, бегущий огонь, дыхание, волна).
 *
 * Модуль предоставляет простой интерфейс для управления анимированными
 * эффектами подсветки на основе WS2812. Каждый эффект рендерится
 * во внутренний буфер (back-buffer) и применяется к ленте вызовом
 * led_refresh(). Состояние эффектов хранится в структуре fx_state_t,
 * доступной через модульные статические переменные.
 *
 * @note Все функции рендера вызываются из одного потока; блокировка
 *       led_lock/led_unlock обеспечивает безопасность при конкурентном
 *       доступе к буферу.
 */

#include <stdint.h>
#include "led_driver/ws2812.h"

/**
 * @brief Перечисление доступных режимов LED-эффектов.
 *
 * Значения >= 2 считаются «активными» эффектами (effects_is_active()).
 * Режимы FX_OFF и FX_STATIC не запускают анимацию.
 */
typedef enum {
    FX_OFF      = 0,   /**< Эффект выключен — все светодиоды погашены */
    FX_STATIC   = 1,   /**< Статический цвет (рендер в отдельной логике) */
    FX_RAINBOW  = 2,   /**< Радужное переливание — плавный переход оттенков по всей ленте */
    FX_RUNNING  = 3,   /**< Бегущий огонь — узкий светящийся сегмент движется вдоль ленты */
    FX_BREATHE  = 4,   /**< Дыхание — плавное нарастание и затухание яркости */
    FX_WAVE     = 5,   /**< Волна — цветовая волна с высокой пространственной частотой */
} fx_mode_t;

/**
 * @brief Состояние текущего LED-эффекта.
 *
 * Содержит все параметры, необходимые для рендера активного эффекта.
 * После вызова effects_set() кадровый счётчик сбрасывается в ноль.
 */
typedef struct {
    uint8_t  mode;     /**< Текущий режим эффекта (значение fx_mode_t) */
    uint8_t  r, g, b;  /**< Базовый цвет RGB для режимов running и breathe */
    uint8_t  speed;    /**< Скорость эффекта (зарезервировано; пока не используется в рендере) */
    uint16_t pixel;    /**< Начальный пиксель для статического режима */
    uint16_t count;    /**< Количество пикселей для статического режима */
} fx_state_t;

/**
 * @brief Инициализация модуля эффектов.
 *
 * Устанавливает режим FX_OFF и обнуляет кадровый счётчик.
 * Должна вызываться один раз при старте системы.
 */
void effects_init(void);

/**
 * @brief Установить параметры эффекта и начать анимацию.
 *
 * Копирует переданную структуру состояния во внутренний буфер
 * и сбрасывает кадровый счётчик. Если mode >= FX_RAINBOW,
 * анимация начнётся с первого кадра.
 *
 * @param[in] state Указатель на заполненную структуру fx_state_t.
 */
void effects_set(const fx_state_t *state);

/**
 * @brief Остановить текущий эффект.
 *
 * Переводит систему в режим FX_OFF; буфер кадра обнуляется
 * при следующем вызове effects_render().
 */
void effects_clear(void);

/**
 * @brief Отрисовать текущий кадр активного эффекта.
 *
 * Если активен эффект с mode >= FX_RAINBOW, функция инкрементирует
 * внутренний кадровый счётчик, вычисляет цвета для каждого пикселя
 * и записывает их в back-buffer. После рендера вызывается
 * led_refresh() для обновления физической ленты.
 *
 * @note Функция не выполняет никаких действий, если mode < 2 (OFF/STATIC).
 */
void effects_render(void);

/**
 * @brief Проверить, активен ли сейчас LED-эффект.
 *
 * @return true если текущий режим >= FX_RAINBOW (анимация запущена),
 *         false если режим FX_OFF или FX_STATIC.
 */
bool effects_is_active(void);
