#include "effects.h"
#include <math.h>

/** Текущее состояние эффекта (инкрементируется модулем). */
static fx_state_t s_fx = { .mode = FX_OFF };

/** Счётчик кадров — увеличивается на 1 при каждом вызове effects_render(). */
static uint32_t   s_frame = 0;

/**
 * @brief Конвертация цвета из HSV в RGB.
 *
 * Использует стандартный алгоритм с разбиением на 6 секторов
 * по значению оттенка (H). Насыщенность (S) и яркость (V)
 * задаются в диапазоне 0–255.
 *
 * @param[in]  h  Оттенок в градусах (0–359, автоматически приводится к модулю 360)
 * @param[in]  s  Насыщенность (0–255)
 * @param[in]  v  Яркость (0–255)
 * @param[out] r  Указатель на результат — компонента красного (0–255)
 * @param[out] g  Указатель на результат — компонента зелёного (0–255)
 * @param[out] b  Указатель на результат — компонента синего (0–255)
 */
static void hsv_to_rgb(int h, int s, int v, uint8_t *r, uint8_t *g, uint8_t *b) {
    h %= 360;
    int c = (v * s) / 255;
    int x = c * (1 - abs((h / 60) % 2 - 1));
    int m = v - c;
    if      (h < 60)  { *r = c; *g = x; *b = 0; }
    else if (h < 120) { *r = x; *g = c; *b = 0; }
    else if (h < 180) { *r = 0; *g = c; *b = x; }
    else if (h < 240) { *r = 0; *g = x; *b = c; }
    else if (h < 300) { *r = x; *g = 0; *b = c; }
    else              { *r = c; *g = 0; *b = x; }
    *r += m; *g += m; *b += m;
}

/**
 * @brief Инициализация модуля эффектов.
 *
 * Устанавливает режим FX_OFF и обнуляет внутренний кадровый счётчик.
 * Должна вызываться один раз при старте системы перед первым
 * вызовом effects_render().
 */
void effects_init(void) {
    s_fx.mode = FX_OFF;
    s_frame = 0;
}

/**
 * @brief Установить параметры эффекта и начать воспроизведение.
 *
 * Полностью копирует переданную структуру состояния во внутренний
 * буфер и сбрасывает кадровый счётчик в ноль, гарантируя
 * воспроизведение эффекта с первого кадра.
 *
 * @param[in] state Указатель на заполненную структуру fx_state_t.
 *                  Содержимое копируется, указатель может быть
 *                  освобождён после вызова.
 */
void effects_set(const fx_state_t *state) {
    s_fx = *state;
    s_frame = 0;
}

/**
 * @brief Остановить текущий эффект.
 *
 * Переводит систему в режим FX_OFF. Кадровый счётчик
 * обнуляется при следующем вызове effects_render().
 */
void effects_clear(void) {
    s_fx.mode = FX_OFF;
}

/**
 * @brief Проверить, активен ли сейчас LED-эффект.
 *
 * Эффект считается активным, если текущий режим >= FX_RAINBOW (2).
 * Режимы FX_OFF (0) и FX_STATIC (1) не являются анимированными.
 *
 * @return true если анимация запущена, false в противном случае.
 */
bool effects_is_active(void) {
    return s_fx.mode >= 2;
}

/**
 * @brief Отрисовать текущий кадр активного эффекта.
 *
 * Если текущий режим < FX_RAINBOW, функция немедленно возвращается.
 * В противном случае выполняется:
 *  1. Инкремент кадрового счётчика s_frame.
 *  2. Получение указателя на back-buffer через led_get_colors().
 *  3. Вычисление цвета каждого пикселя в зависимости от режима.
 *  4. Обновление физической ленты через led_refresh().
 *
 * Поддерживаемые режимы:
 *  - FX_RAINBOW — радужное переливание (постоянное движение оттенка).
 *  - FX_RUNNING — бегущий огонь (узкий сегмент с затуханием к краям).
 *  - FX_BREATHE — дыхание (синусоидальная модуляция яркости).
 *  - FX_WAVE    — цветовая волна (высокая пространственная частота).
 *
 * @note Буфер блокируется на время записи (led_lock/led_unlock)
 *       для обеспечения потокобезопасности.
 */
void effects_render(void) {
    if (s_fx.mode < 2) return;

    uint16_t count = led_get_count(0);
    if (count == 0) return;

    s_frame++;

    led_lock(0);
    led_color_t *back = led_get_colors(0);

    switch (s_fx.mode) {
    /**
     * Радужное переливание (FX_RAINBOW):
     * Каждый пиксель получает оттенок, пропорциональный его позиции
     * на ленте, с учётом текущего кадра. Оттенок вычисляется как
     * (i * 360 / count + s_frame * 3) % 360, что создаёт плавное
     * перемещение радуги вдоль ленты.
     */
    case FX_RAINBOW:
        for (uint16_t i = 0; i < count; i++) {
            int hue = (i * 360 / count + s_frame * 3) % 360;
            hsv_to_rgb(hue, 255, 255, &back[i].r, &back[i].g, &back[i].b);
        }
        break;

    /**
     * Бегущий огонь (FX_RUNNING):
     * Узкий светящийся сегмент (радиус 5 пикселей) движется
     * вдоль ленты с постоянной скоростью. Яркость уменьшается
     * линейно с расстоянием от центра сегмента. Базовый цвет
     * задаётся полями r, g, b структуры fx_state_t.
     */
    case FX_RUNNING: {
        int pos = s_frame % (count + 10);
        for (uint16_t i = 0; i < count; i++) {
            int dist = abs(i - pos);
            if (dist < 5) {
                uint8_t br = 255 - (dist * 51);
                back[i].r = (s_fx.r * br) / 255;
                back[i].g = (s_fx.g * br) / 255;
                back[i].b = (s_fx.b * br) / 255;
            } else {
                back[i].r = 0;
                back[i].g = 0;
                back[i].b = 0;
            }
        }
        break;
    }

    /**
     * Дыхание (FX_BREATHE):
     * Яркость всех пикселей модулируется по синусоиде с периодом
     * 120 кадров. Фаза вычисляется как 2π * (s_frame % 120) / 120,
     * а результирующая яркость — (sin(phase) + 1) / 2 * 255.
     * Базовый цвет задаётся полями r, g, b.
     */
    case FX_BREATHE: {
        float phase = (float)(s_frame % 120) / 120.0f * 3.14159f * 2.0f;
        float br = (sinf(phase) + 1.0f) / 2.0f;
        uint8_t bv = (uint8_t)(br * 255);
        for (uint16_t i = 0; i < count; i++) {
            back[i].r = (s_fx.r * bv) / 255;
            back[i].g = (s_fx.g * bv) / 255;
            back[i].b = (s_fx.b * bv) / 255;
        }
        break;
    }

    /**
     * Цветовая волна (FX_WAVE):
     * Аналогично радуге, но с увеличенной пространственной
     * частотой (умножитель 5 вместо 360/count) и несколько
     * иной скоростью движения (s_frame * 4). Насыщенность
     * снижена до 200 для более мягкого оттенка.
     */
    case FX_WAVE:
        for (uint16_t i = 0; i < count; i++) {
            int hue = (i * 5 + s_frame * 4) % 360;
            hsv_to_rgb(hue, 200, 255, &back[i].r, &back[i].g, &back[i].b);
        }
        break;

    default:
        break;
    }

    led_unlock(0);
    led_refresh(0);
    led_refresh(1);
}
