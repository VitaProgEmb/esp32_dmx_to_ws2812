#pragma once

/**
 * @file patch_manager.h
 * @brief Менеджер таблиц патчей (сопоставление DMX-адресов → светильники/LED).
 *
 * Модуль управляет глобальной таблицей патчей (patch_map_t), которая
 * определяет, как DMX-адреса universumов отображаются на отдельные
 * светильники (фикстуры). Таблица хранится в энергонезависимой памяти
 * и может загружаться/сохраняться в форматах CSV и JSON.
 *
 * Каждая запись патча (patch_entry_t) описывает один светильник:
 * его universe, DMX start-адрес и флаг пропуска. Таблица поддерживает
 * до PATCH_MAX_ENTRIES записей.
 *
 * @note Таблица патчей — глобальная переменная g_patch; доступ к ней
 *       должен быть синхронизирован при конкурентном использовании.
 */

#include <stdint.h>
#include <stdbool.h>

/**
 * @brief Максимальное количество записей в таблице патчей.
 *
 * Определяет размер массива entries[] в структуре patch_map_t.
 * Значение 340 позволяет охватить до 340 DMX-светильников
 * в одной конфигурации.
 */
#define PATCH_MAX_ENTRIES  340

/**
 * @brief Одна запись патча — сопоставление DMX-адреса с фикстурой.
 *
 * Описывает один DMX-светильник: его universe (номер DMX- universum),
 * начальный DMX-адрес (1–512) и флаг пропуска. Записи с skip=true
 * игнорируются при рендере DMX-данных.
 */
typedef struct {
    uint8_t  universe;   /**< Номер DMX- universum (0–255) */
    uint16_t dmx_addr;   /**< DMX start-адрес светильника (1–512) */
    bool     skip;       /**< Флаг пропуска: true — светильник не обрабатывается */
} patch_entry_t;

/**
 * @brief Карта патчей — массив записей с общим счётчиком.
 *
 * Содержит массив patch_entry_t фиксированного размера
 * и текущее количество активных записей. Количество записей
 * не может превышать PATCH_MAX_ENTRIES.
 */
typedef struct {
    patch_entry_t entries[PATCH_MAX_ENTRIES]; /**< Массив записей патчей */
    uint16_t      count;                      /**< Текущее количество записей в массиве */
} patch_map_t;

/** Глобальная таблица патчей, доступная из любого модуля. */
extern patch_map_t g_patch;

/**
 * @brief Инициализация менеджера патчей.
 *
 * Устанавливает count = 0 и флаг skip = false для всех записей.
 * Должна вызываться один раз при старте системы.
 */
void     patch_init(void);

/**
 * @brief Загрузить таблицу патчей из энергонезависимой памяти (NVS).
 *
 * Если сохранённая версия отсутствует или повреждена, используется
 * пустая таблица (count = 0).
 */
void     patch_load(void);

/**
 * @brief Сохранить текущую таблицу патчей в энергонезависимую память (NVS).
 *
 * Сериализует содержимое g_patch и записывает его в NVS-хранилище.
 * Вызывается после каждого изменения таблицы.
 */
void     patch_save(void);

/**
 * @brief Применить таблицу патчей из CSV-строки.
 *
 * Парсит текст в формате CSV и заполняет g_patch. Старое содержимое
 * таблицы заменяется. Формат строки:
 *   universe,dmx_addr,skip
 *
 * @param[in] csv_text Строка с данными CSV (терминируется '\0').
 */
void     patch_apply_from_csv(const char *csv_text);

/**
 * @brief Преобразовать текущую таблицу патчей в CSV-строку.
 *
 * Выделяет память через malloc() и возвращает строку в формате:
 *   universe,dmx_addr,skip\\n
 *
 * @return Указатель на строку CSV (освободить через free()) или NULL
 *         при ошибке выделения памяти.
 */
char*    patch_to_csv_string(void);

/**
 * @brief Преобразовать текущую таблицу патчей в JSON-строку.
 *
 * Выделяет память через malloc() и возвращает JSON-массив объектов:
 *   [{"universe":0,"dmx_addr":1,"skip":false}, ...]
 *
 * @return Указатель на строку JSON (освободить через free()) или NULL
 *         при ошибке выделения памяти.
 */
char*    patch_to_json_string(void);

/**
 * @brief Добавить диапазон патчей в таблицу.
 *
 * Создаёт count записей, начиная с fixtures[start_fixture].
 * Universe для каждой записи устанавливается равным параметру universe.
 * DMX-адрес рассчитывается автоматически (start_fixture + i + 1).
 *
 * @param[in] universe       Номер DMX- universum для диапазона.
 * @param[in] start_fixture  Номер первого фикстуры (0-based индекс).
 * @param[in] count          Количество фикстур в диапазоне.
 *
 * @return true если диапазон успешно добавлен (достаточно места в таблице),
 *         false если не хватает места или параметры некорректны.
 */
bool     patch_add_range(uint8_t universe, uint16_t start_fixture, uint16_t count);

/**
 * @brief Удалить диапазон патчей из таблицы.
 *
 * Удаляет count записей начиная с индекса start_fixture.
 * Оставшиеся записи сдвигаются в начало массива, count уменьшается.
 *
 * @param[in] start_fixture  Индекс первой удаляемой записи (0-based).
 * @param[in] count          Количество удаляемых записей.
 *
 * @return true если диапазон успешно удалён,
 *         false если диапазон выходит за пределы таблицы.
 */
bool     patch_del_range(uint16_t start_fixture, uint16_t count);
