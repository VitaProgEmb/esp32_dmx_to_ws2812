/**
 * @enum led_mode_t
 * @brief Режим работы двух светодиодных лент WS2812B.
 *
 * Определяет, как DMX-данные распределяются между двумя лентами:
 *
 *   - LED_MODE_PARALLEL (0): параллельный режим.
 *       Каждая лента получает данные со своего DMX-порта:
 *         Strip 1 ← DMX-порт 0 (данные для fixtures 0..N-1).
 *         Strip 2 ← DMX-порт 1 (данные для fixtures 0..N-1).
 *       Две ленты работают независимо, каждая со своим набором DMX-адресов.
 *
 *   - LED_MODE_SEQUENTIAL (1): последовательный режим.
 *       Одна лента (из 2000 LED) получает данные с обоих DMX-портов:
 *         Fixtures 0..N/2-1 ← DMX-порт 0.
 *         Fixtures N/2..N-1 ← DMX-порт 1.
 *       Оба порта питают одну ленту, DMX-адреса разделяются пополам.
 *
 * @note Переключение режима возможно во время работы (переменная g_led_mode).
 */
typedef enum {
    LED_MODE_PARALLEL   = 0,  /**< @brief Параллельный режим: strip1 ← port0, strip2 ← port1 */
    LED_MODE_SEQUENTIAL = 1,  /**< @brief Последовательный режим: одна лента, два DMX-порта */
} led_mode_t;

/**
 * @def LED_DEFAULT_MODE
 * @brief Режим работы двух LED-лент по умолчанию.
 *
 * Определяет начальный режим при старте системы. Может быть изменён
 * через веб-интерфейс или API во время работы.
 *
 * @note По умолчанию: LED_MODE_PARALLEL (параллельный режим).
 */
#define LED_DEFAULT_MODE  LED_MODE_PARALLEL
