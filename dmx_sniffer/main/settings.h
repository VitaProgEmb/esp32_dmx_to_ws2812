/**
 * @file settings.h
 * @brief Глобальные настройки конфигурации DMX Sniffer / Tester
 *
 * Содержит все аппаратные настройки (выводы GPIO), параметры Wi-Fi сетей
 * для отладки (STA) и релиза (AP), а также дефолтные значения параметров,
 * которые используются при первом запуске устройства.
 */

#pragma once

// =========================================================================
// НАСТРОЙКИ СЕТИ WI-FI
// =========================================================================

/**
 * Режим работы Wi-Fi модуля:
 *  - false (STA) - устройство подключается к домашней/рабочей сети (для отладки)
 *  - true  (AP)  - устройство само создает точку доступа (для релизной версии)
 */
#define WIFI_MODE_AP_RELEASE   false


/** Имя создаваемой точки доступа (AP Mode) */
#define WIFI_AP_SSID           "Fountain_Config"
/** Пароль для точки доступа (минимум 8 символов, пустая строка - открытая сеть) */
#define WIFI_AP_PASS           ""
/** Номер Wi-Fi канала для AP */
#define WIFI_AP_CHANNEL        11
/** Максимальное количество одновременно подключенных клиентов */
#define WIFI_AP_MAX_CONN       4

/** SSID внешней сети для подключения (STA Mode) */
#define WIFI_STA_SSID          "VP"
/** Пароль внешней сети (STA Mode) */
#define WIFI_STA_PASS          "Atmega328"

// =========================================================================
// НАСТРОЙКИ КНОПКИ BOOT И СТАТУСНОГО LED
// =========================================================================

/** GPIO пин кнопки BOOT (активна LOW) */
#define BOOT_BUTTON_GPIO       0
/** GPIO пин статусного LED (WiFi индикация) */
#define STATUS_LED_GPIO        12

// =========================================================================
// НАСТРОЙКИ DMX-ПОРТОВ (GPIO)
// =========================================================================

/** GPIO пин приема (RX) для Первого DMX порта */
#define DMX_GPIO_RX1           15
/** GPIO пин передачи (TX) для Первого DMX порта */
#define DMX_GPIO_TX1           2

/** GPIO пин приема (RX) для Второго DMX порта */
#define DMX_GPIO_RX2           16
/** GPIO пин передачи (TX) для Второго DMX порта */
#define DMX_GPIO_TX2           17
/** GPIO пин направления (DIR/RTS) для Второго DMX порта */
#define DMX_GPIO_DIR2          27

// =========================================================================
// НАСТРОЙКИ АДРЕСНОЙ СВЕТОДИОДНОЙ ЛЕНТЫ (WS2812)
// =========================================================================

/** GPIO пин для передачи данных (RMT TX) на светодиодную ленту WS2812 */
#define LED_STRIP_GPIO         23
/** Максимальное количество поддерживаемых светодиодов в ленте */
#define LED_STRIP_MAX_LEDS     1000

// =========================================================================
// ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ (если настройки в NVS отсутствуют)
// =========================================================================

/** Дефолтный режим работы DMX (DMX_MODE_SNIFFER или DMX_MODE_TESTER) */
#define DMX_DEFAULT_MODE       DMX_MODE_SNIFFER
/** Количество WS2812 светодиодов по умолчанию */
#define LED_DEFAULT_COUNT      100
/** Реверс порядка светодиодов по умолчанию */
#define LED_DEFAULT_REVERSE    false
/** Порядок следования цветов в приборе (CH_ORDER_RGB, CH_ORDER_GRB и т.д.) */
#define FIXTURE_CH_ORDER       CH_ORDER_RGB

/** Резервный цвет (Красный) при отсутствии DMX сигнала */
#define FALLBACK_COLOR_R       0
/** Резервный цвет (Зеленый) при отсутствии DMX сигнала */
#define FALLBACK_COLOR_G       0
/** Резервный цвет (Синий) при отсутствии DMX сигнала */
#define FALLBACK_COLOR_B       255
/** Таймаут отсутствия DMX сигнала (в миллисекундах) до перехода на резервный цвет */
#define FALLBACK_TIMEOUT_MS    100

/** Дефолтное состояние интерполяции (сглаживания) WS2812 ленты */
#define LED_DEFAULT_INTERPOLATE true

