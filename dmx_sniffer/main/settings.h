/**
 * @name Режим приёма DMX-данных
 * @{
 */

/**
 * @def DMX_SW_UART_MODE
 * @brief Режим приёма DMX-данных через программный/аппаратный UART.
 *
 * Определяет метод захвата DMX-сигнала на GPIO-входах:
 *   - 0 (GPIO edge timing): прерывания на каждый фронт/спад сигнала.
 *     CPU обрабатывает каждый.edges (~500kHz ISR). Самый нагруженный режим.
 *   - 1 (RMT RX): аппаратный захват через DMA модуль RMT.
 *     CPU не участвует в захвате данных — минимальная нагрузка.
 *   - 2 (HW UART RX): прямой доступ к регистрам аппаратного UART,
 *     собственный ISR с глобальным spinlock. Быстрый и надёжный вариант.
 *
 * @note По умолчанию: 2 (HW UART RX).
 * @note Режим 1 (RMT RX) требует выделения RMT-каналов (см. DMX_RMT_RX_CH_PORTx).
 * @note Режим 0 (GPIO edge) наиболее нагружен, рекомендуется только для отладки.
 */
#define DMX_SW_UART_MODE       2

/** @} */ /* конец группы DMX-режим */

/* ========================================================================
 * НАСТРОЙКИ RMT RX (для режима DMX_SW_UART_MODE = 1)
 * ======================================================================== */

/**
 * @name Параметры RMT RX для приёма DMX
 * @{
 */

/**
 * @def DMX_RMT_CLK_HZ
 * @brief Тактовая частота RMT RX модуля (в Гц).
 *
 * Устанавливает разрешение таймера RMT: 1 МГц = 1 тик = 1 мкс.
 * DMX работает на скорости 250 кбит/с → 4 тика на один бит (при 1 МГц).
 *
 * @note Рекомендуемое значение: 1000000 (1 МГц).
 */
#define DMX_RMT_CLK_HZ         1000000

/**
 * @def DMX_RMT_IDLE_US
 * @brief Таймаут idle-состояния RMT RX (в микросекундах).
 *
 * Если на входе RMT нет активности более DMX_RMT_IDLE_US мкс,
 * кадр считается завершённым. Между кадрами DMX есть пауза (BREAK)
 * длительностью ≥ 88 мкс. Значение 200 мкс обеспечивает запас.
 *
 * @note Используется как signal_range_max_ns = DMX_RMT_IDLE_US * 1000.
 */
#define DMX_RMT_IDLE_US        200

/**
 * @def DMX_RMT_RX_CH_PORT0
 * @brief Номер RMT-канала для приёма DMX на первом порту (RX1).
 *
 * Канал назначается вручную, чтобы не конфликтовать с RMT TX-каналом
 * для LED-ленты (автовыбор). При конфликте будет ошибка при init.
 *
 * @note По умолчанию: 1.
 */
#define DMX_RMT_RX_CH_PORT0   1

/**
 * @def DMX_RMT_RX_CH_PORT1
 * @brief Номер RMT-канала для приёма DMX на втором порту (RX2).
 *
 * Аналогично DMX_RMT_RX_CH_PORT0, но для второго DMX-входа.
 *
 * @note По умолчанию: 2.
 */
#define DMX_RMT_RX_CH_PORT1   2

/** @} */ /* конец группы RMT RX */

/* ========================================================================
 * МАТРИЦА КОММУТАЦИИ RX-ПОРТОВ
 * ======================================================================== */

/**
 * @def DMX_RX_ROUTING_MATRIX
 * @brief Режим маршрутизации DMX RX-портов.
 *
 * Определяет, какие физические GPIO-выводы слушают RX-каналы RMT:
 *   - 0 (нормальный / ПРОДАКШН): каждый порт слушает свой физический пин.
 *       Порт 0 → GPIO 15 (RX1), Порт 1 → GPIO 16 (RX2).
 *       Используется для двойного DMX-входа (два независимых кабеля).
 *   - 1 (тестовый / отладка): оба порта слушают один GPIO (RX1).
 *       Удобно для отладки — один кабель = оба порта получают данные.
 *
 * @note По умолчанию: 0 (нормальный режим).
 */
#define DMX_RX_ROUTING_MATRIX 0

/**
 * @def DMX_RMT_RX_BUF_SIZE
 * @brief Размер буфера RMT RX (в символах).
 *
 * Каждый символ RMT состоит из 2 уровней × 2 длительностей (level0,
 * duration0, level1, duration1). DMX-кадр = 513 байт × ~2 символа/байт
 * ≈ 1026 символов. С запасом устанавливается 1200.
 *
 * @note При увеличении буфера увеличивается потребление RAM.
 */
#define DMX_RMT_RX_BUF_SIZE   1200

