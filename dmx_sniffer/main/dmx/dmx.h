#pragma once

/**
 * @file dmx.h
 * @brief Заголовочный файл DMX512 UART HAL — чистый аппаратный абстрактный уровень
 *
 * Данный модуль реализует чистый HAL (Hardware Abstraction Layer) для протокола DMX512
 * на базе UART. Поддерживает два порта с независимым приёмом и передачей.
 *
 * Параметры протокола DMX512:
 *   - Скорость передачи: 250 кбит/с (250000 бод)
 *   - Формат данных: 8N2 (8 данных, без проверки чётности, 2 стоп-бита)
 *   - Количество каналов: 512 (нумерация с 1 до 512)
 *   - Длина кадра: 513 байт (1 старт-код + 512 каналов данных)
 *   - Размер прерывания: минимум 88 мкс (11 бит × 4 мкс)
 *
 * Модуль поддерживает три режима работы:
 *   - SNIFFER (подслушивание): приём DMX данных с двух портов
 *   - TESTER (тестер): генерация DMX данных на выбранный порт
 *   - PATCH (проходной): DMX данные проходят через устройство без изменений
 *
 * @note Модуль не содержит логики управления LED, fallback-механизмов или эффектов.
 *       Это чистый UART HAL для работы с DMX512.
 */

#include <stdint.h>
#include <stdbool.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "freertos/semphr.h"
#include "freertos/event_groups.h"

/* ===== Константы ===== */

/**
 * @brief Максимальное количество DMX каналов в одном кадре
 * @details В протоколе DMX512 используется нумерация каналов от 1 до 512,
 *          что соответствует 512 каналам данных. Нулевой байт — старт-код.
 */
#define DMX_CHANNELS     512

/**
 * @brief Полная длина DMX кадра в байтах
 * @details Включает 1 байт старт-кода + 512 байт данных каналов.
 *          Старт-код всегда равен 0x00 для.standard DMX512.
 */
#define DMX_FRAME_LEN    513

/**
 * @brief Индекс первого DMX порта (UART1)
 */
#define DMX_PORT_1       0

/**
 * @brief Индекс второго DMX порта (UART2)
 */
#define DMX_PORT_2       1

/**
 * @brief Общее количество DMX портов
 */
#define DMX_PORT_COUNT   2

/**
 * @brief Бит для события получения кадра на первом порту
 * @details Используется в EventGroupHandle_t g_dmx_events для уведомления
 *          о завершении приёма кадра DMX на порту 0.
 */
#define DMX_EVT_FRAME0   BIT0

/**
 * @brief Бит для события получения кадра на втором порту
 * @details Используется в EventGroupHandle_t g_dmx_events для уведомления
 *          о завершении приёма кадра DMX на порту 1.
 */
#define DMX_EVT_FRAME1   BIT1

/* ===== Типы ===== */

/**
 * @brief Режимы работы DMX модуля
 * @details Определяет, как модуль будет работать с DMX данными.
 *          Режим влияет на направление потока данных и поведение UART.
 */
typedef enum {
    DMX_MODE_SNIFFER = 0,  /**< Режим подслушивания — приём DMX данных с обоих портов */
    DMX_MODE_TESTER  = 1,  /**< Режим тестера — генерация DMX данных на выбранный порт */
    DMX_MODE_PATCH   = 2   /**< Режим проходного — DMX данные проходят без изменений */
} dmx_mode_t;

/**
 * @brief Режимы передачи данных в тестере
 * @details Определяет, как формируется DMX кадр в режиме TESTER.
 */
typedef enum {
    TX_MODE_POINT = 0,  /**< Точечный режим — передача одного RGB тройки на указанный канал */
    TX_MODE_FILL  = 1   /**< Режим заполнения — передача одного RGB тройки на несколько тройков подряд */
} tx_mode_t;

/**
 * @brief Структура для хранения необработанного DMX кадра
 * @details Содержит сырые данные последнего принятого кадра DMX,
 *          включая метаданные о времени получения.
 */
typedef struct {
    uint8_t  data[512];      /**< Массив данных каналов DMX (без старт-кода), максимум 512 байт */
    uint16_t len;            /**< Фактическая длина полученных данных в байтах (1..512) */
    uint32_t timestamp_ms;   /**< Временная метка получения кадра в миллисекундах (from esp_timer) */
} dmx_raw_frame_t;

/**
 * @brief Размер кольцевого буфера контрольных сумм
 * @details Определяет количество хранимых контрольных сумм для каждого порта.
 *          Используется степень двойки для быстрого вычисления индекса через маскирование.
 */
#define CK_RING_SIZE 1024

/**
 * @brief Запись контрольной суммы DMX кадра
 * @details Содержит XOR и суммарную контрольные суммы принятого кадра.
 *          Используется для анализа целостности DMX данных.
 */
typedef struct {
    uint16_t xor_val;     /**< XOR-сумма всех байтов данных кадра (без старт-кода) */
    uint16_t sum_val;     /**< Арифметическая сумма всех байтов данных кадра */
    uint16_t frame_len;   /**< Полная длина кадра включая старт-код (от 2 до 513) */
} dmx_ck_entry_t;

/**
 * @brief Кольцевой буфер контрольных сумм
 * @details Хранит контрольные суммы последних принятых кадров DMX для каждого порта.
 *          Используется для мониторинга целостности данных и статистики.
 */
typedef struct {
    dmx_ck_entry_t buf[CK_RING_SIZE];  /**< Массив записей контрольных сумм */
    volatile uint32_t count;            /**< Общее количество записанных записей (используется для вычисления индекса) */
} dmx_ck_ring_t;

/**
 * @brief Состояние DMX модуля
 * @details Хранит текущее состояние работы модуля, включая режим,
 *          параметры передачи и статистику.
 */
typedef struct {
    volatile dmx_mode_t  mode;           /**< Текущий режим работы модуля (SNIFFER/TESTER/PATCH) */
    volatile uint8_t     tx_port;        /**< Выбранный порт для передачи (0 или 1, или оба) */
    volatile uint16_t    tx_channel;     /**< Начальный канал для передачи в режиме TESTER */
    volatile uint8_t     tx_r, tx_g, tx_b;  /**< Значения RGB для передачи в режиме TESTER (0..255) */
    volatile tx_mode_t   tx_mode;        /**< Режим передачи (точечный или заполнение) */
    volatile uint16_t    tx_count;       /**< Количество тройки каналов для заполнения в режиме TX_MODE_FILL */
    volatile uint32_t    last_rx_ms[DMX_PORT_COUNT];  /**< Время последнего приема для каждого порта (мс) */
    volatile int         patch_cursor;   /**< Курсор для режима PATCH (начальный канал) */
    volatile int         patch_universe; /**< вселенная для режима PATCH (1 или 2) */
} dmx_state_t;

/* ===== Дефолты ===== */

/**
 * @brief Режим работы по умолчанию
 * @details При включении модуль работает в режиме подслушивания (SNIFFER).
 */
#define DMX_DEFAULT_MODE  DMX_MODE_SNIFFER

/* ===== Глобалы ===== */

/**
 * @brief Глобальное состояние DMX модуля
 * @details Хранит текущие настройки и параметры работы модуля.
 *          Доступ к этому объекту должен осуществляться через dmx_lock/dmx_unlock.
 */
extern dmx_state_t       g_dmx;

/**
 * @brief Группа событий для уведомления о получении DMX кадров
 * @details Используется FreeRTOS EventGroup для синхронизации задач.
 *          Биты DMX_EVT_FRAME0 и DMX_EVT_FRAME1 устанавливаются при получении кадра.
 */
extern EventGroupHandle_t g_dmx_events;

/**
 * @brief Массив последних полученных DMX кадров
 * @details Содержит необработанные данные последних кадров для каждого порта.
 *          Индекс 0 — порт 1, индекс 1 — порт 2.
 */
extern dmx_raw_frame_t    g_raw_frames[2];

/**
 * @brief Массив кольцевых буферов контрольных сумм
 * @details Хранит контрольные суммы последних принятых кадров для каждого порта.
 *          Используется для мониторинга целостности данных.
 */
extern dmx_ck_ring_t      g_ck_rings[2];

/**
 * @brief Счетчик прерываний для каждого порта
 * @details Увеличивается при каждом срабатывании ISR для отладки и мониторинга.
 */
extern volatile uint32_t  g_isr_count[2];

/**
 * @brief Счетчик обнаруженных break-сигналов для каждого порта
 * @details Увеличивается при обнаружении break в DMX кадре (начало нового кадра).
 */
extern volatile uint32_t  g_break_count[2];

/* ===== API ===== */

/**
 * @brief Тип callback-функции для обработки полученных DMX кадров
 * @param port Номер порта (0 или 1), на котором получен кадр
 * @details Функция вызывается после успешного получения и обработки кадра DMX.
 *          Вызывается из контекста задачи dmx_rx_task.
 */
typedef void (*dmx_frame_cb_t)(int port);

/**
 * @brief Инициализация DMX модуля
 * @param tx1 GPIO пин передатчика первого порта (UART1 TX)
 * @param tx2 GPIO пин передатчика второго порта (UART2 TX)
 * @param rx1 GPIO пин приемника первого порта (UART1 RX)
 * @param rx2 GPIO пин приемника второго порта (UART2 RX)
 * @param dir GPIO пин управления направлением (RS485 DE/RE), -1 если не используется
 * @details Создает мьютекс, инициализирует UART для обоих портов с параметрами DMX512,
 *          запускает задачи приема и передачи. Порт 1 всегда инициализируется,
 *          порт 2 — опционально (если dir >= 0).
 */
void dmx_init(int tx1, int tx2, int rx1, int rx2, int dir);

/**
 * @brief Чтение данных из последнего полученного DMX кадра
 * @param port Номер порта (0 или 1)
 * @param buf Указатель на буфер для чтения данных
 * @param len Максимальное количество байт для чтения
 * @details Читает данные каналов DMX из g_raw_frames[port].data.
 *          Данные копируются с защитой от конкурентного доступа через мьютекс.
 *          Если порт недействителен, функция ничего не делает.
 */
void dmx_read(int port, uint8_t *buf, int len);

/**
 * @brief Отправка DMX кадра на указанный порт
 * @param port Номер порта (0 или 1)
 * @param frame Указатель на массив данных для отправки (включая старт-код)
 * @param len Длина данных для отправки в байтах
 * @details Отправляет данные через UART с генерацией break-сигнала.
 *          Функция блокирующая — ждет завершения передачи.
 *          Если порт недействителен, функция ничего не делает.
 */
void dmx_write(int port, const uint8_t *frame, int len);

/**
 * @brief Установка режима работы DMX модуля
 * @param m Режим работы (DMX_MODE_SNIFFER, DMX_MODE_TESTER, DMX_MODE_PATCH)
 * @details Переключает режим работы модуля. При переключении в режим TESTER или PATCH
 *          отключается прием на обоих портах и устанавливается направление передачи.
 *          При переключении в SNIFFER — включается прием и устанавливается направление приема.
 *          Изменение режима логируется через ESP_LOGI.
 */
void dmx_set_mode(dmx_mode_t m);

/**
 * @brief Регистрация callback-функции для обработки полученных DMX кадров
 * @param cb Указатель на callback-функцию или NULL для отмены регистрации
 * @details Функция вызывается из контекста задачи dmx_rx_task после обработки кадра.
 *          Регистрация нового callback заменяет предыдущий.
 */
void dmx_on_frame(dmx_frame_cb_t cb);

/**
 * @brief Захват мьютекса для доступа к глобальным данным DMX
 * @details Блокирует доступ к g_dmx и другим общим данным.
 *          Используется для безопасного доступа из разных задач.
 *          Если мьютекс не создан, функция ничего не делает.
 */
void dmx_lock(void);

/**
 * @brief Освобождение мьютекса для доступа к глобальным данным DMX
 * @details Разблокирует доступ к g_dmx и другим общим данным.
 *          Должна вызываться после завершения работы с общими данными.
 *          Если мьютекс не создан, функция ничего не делает.
 */
void dmx_unlock(void);
